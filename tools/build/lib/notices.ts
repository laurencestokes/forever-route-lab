import { copyFileSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { compareStrings } from './fs';
import {
  readPackageLegalFiles,
  readPackageRepository,
  type Inclusion,
  type PackageFileText,
  type ShippedPackage,
} from './packages';

export interface NoticeEntry {
  readonly name: string;
  readonly version: string;
  readonly licence: string;
  readonly repository: string | null;
  readonly inclusion: Inclusion;
  readonly reason: string | null;
  readonly licenceFiles: readonly PackageFileText[];
  readonly noticeFiles: readonly PackageFileText[];
}

const RULE = '='.repeat(80);
const THIN_RULE = '-'.repeat(80);

export const TRUNCATION_NOTE =
  "[The rest of this file lists the licences of the package's own bundled dependencies, which do not reach this build.]";

/** Cuts `text` before the first line equal to `until`, leaving a note; unchanged when absent. */
export function truncateLicenceText(text: string, until: string | null): string {
  if (until === null) return text;
  const lines = text.split('\n');
  const index = lines.indexOf(until);
  if (index < 0) return text;
  const kept = lines.slice(0, index).join('\n').replace(/\s+$/, '');
  return `${kept}\n\n${TRUNCATION_NOTE}`;
}

/** Reads repository, licence and NOTICE files for each shipped package from its install directory. */
export function collectNoticeEntries(packages: readonly ShippedPackage[]): readonly NoticeEntry[] {
  return packages.map((pkg) => {
    const legal = readPackageLegalFiles(pkg.directory);
    const licenceFiles = legal.licences.map((file) => ({ file: file.file, text: truncateLicenceText(file.text, pkg.licenceTextUntil) }));
    return {
      name: pkg.name,
      version: pkg.version,
      licence: pkg.licence,
      repository: readPackageRepository(pkg.directory),
      inclusion: pkg.inclusion,
      reason: pkg.reason,
      licenceFiles,
      noticeFiles: legal.notices,
    };
  });
}

/**
 * Renders dist/third-party-notices.txt. The output depends only on the entries (sorted here by
 * name and version), never on the clock or on install paths, so identical inputs give identical
 * bytes.
 */
export function renderThirdPartyNotices(projectName: string, entries: readonly NoticeEntry[]): string {
  const sorted = [...entries].sort((a, b) => compareStrings(a.name, b.name) || compareStrings(a.version, b.version));
  const out: string[] = [
    `${projectName}: third-party software notices`,
    RULE,
    '',
    'This build includes code from the third-party packages listed below: every production',
    'dependency, and the development dependencies whose own code the bundler injects into the',
    'build. For each package this file gives its name, version, declared licence, repository and',
    'the full text of the licence (and NOTICE) files it ships.',
    '',
    `${projectName} itself is licensed GPL-3.0-or-later; see LICENSE.txt. Notices for the game`,
    'data and map geometry are in data/NOTICE.md and maps/placeholder/NOTICE.md where present,',
    'and in THIRD_PARTY_NOTICES.md in the source repository.',
    '',
    `Generated by tools/build/third-party-notices.ts. Packages: ${String(sorted.length)}.`,
    '',
    ...sorted.map((entry) => `  - ${entry.name} ${entry.version} (${entry.licence})`),
  ];
  for (const entry of sorted) {
    out.push(
      '',
      RULE,
      `${entry.name} ${entry.version}`,
      RULE,
      `Licence (declared): ${entry.licence}`,
      `Repository: ${entry.repository ?? 'not declared'}`,
      entry.inclusion === 'production'
        ? 'Included as: production dependency'
        : `Included as: development dependency bundled into the build (${entry.reason ?? 'no reason recorded'})`,
    );
    if (entry.licenceFiles.length === 0) {
      out.push('', `No licence file was found in the package. Its declared licence is ${entry.licence}.`);
    }
    for (const file of [...entry.licenceFiles, ...entry.noticeFiles]) {
      out.push('', THIN_RULE, `${file.file}:`, THIN_RULE, '', file.text);
    }
  }
  return `${out.join('\n')}\n`;
}

export interface WriteNoticesOptions {
  readonly distDir: string;
  /** The repository's LICENSE file, copied to dist/LICENSE.txt. */
  readonly licencePath: string;
  readonly projectName: string;
  readonly entries: readonly NoticeEntry[];
}

/** Writes dist/third-party-notices.txt and dist/LICENSE.txt. dist/ must already exist. */
export function writeDistNotices(options: WriteNoticesOptions): void {
  if (!existsSync(options.distDir)) throw new Error(`${options.distDir} does not exist; run vite build first`);
  if (!existsSync(options.licencePath)) throw new Error(`licence file ${options.licencePath} does not exist`);
  writeFileSync(join(options.distDir, 'third-party-notices.txt'), renderThirdPartyNotices(options.projectName, options.entries));
  copyFileSync(options.licencePath, join(options.distDir, 'LICENSE.txt'));
}
